// Structured outputs may reject the bounds zod emits (integer limits, minLength), so every bound keyword
// is removed from the schema the model sees. QuoteDraftSchema.safeParse enforces them after the run.
function stripBounds(node: unknown, isPropertyMap: boolean): unknown {
  if (Array.isArray(node)) return node.map((n) => stripBounds(n, false));
  if (node === null || typeof node !== "object") return node;
  const out: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(node)) {
    // Inside a "properties" map the keys are field names, never schema keywords.
    if (!isPropertyMap && (SCHEMA_BOUND_KEYS as readonly string[]).includes(key)) continue;
    out[key] = stripBounds(value, !isPropertyMap && key === "properties");
  }
  return out;
}
