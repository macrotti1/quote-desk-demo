function repeatedKind(list: readonly { kind: string }[]): string | undefined {
  const kinds = list.map((a) => a.kind);
  return kinds.find((k, i) => kinds.indexOf(k) !== i);
}
function stockFaultParses(spec: string): boolean {
  try {
    parseStockFault(spec);
    return true;
  } catch {
    return false;
  }
}
export const EvalCaseSchema = z.strictObject({ id: text, category: CaseCategorySchema, rfqId: text,
  stockFault: z.string().refine(stockFaultParses, "invalid stock fault"), faultSeed: z.number().int().optional(),
  approve: z.enum(["approve", "decline"]), note: z.string(), assert: z.array(AssertionSchema) });
export const CasesFileSchema = z.strictObject({ schema: z.literal(1), set: CaseSetSchema, rfqsFile: text,
  truthFile: text, defaults: z.array(AssertionSchema), cases: z.array(EvalCaseSchema) })
  .superRefine((f, ctx) => {
    const ids = f.cases.map((c) => c.id);
    const duplicateId = ids.find((id, i) => ids.indexOf(id) !== i);
    if (duplicateId !== undefined) ctx.addIssue({ code: "custom", message: `duplicate case id: ${duplicateId}` });
    for (const c of f.cases) {
      // A case's assertions are added to the defaults, so a kind may appear once across both lists.
      const twice = repeatedKind([...f.defaults, ...c.assert]);
      if (twice !== undefined) {
        ctx.addIssue({ code: "custom", message: `${c.id}: assertion kind "${twice}" appears twice, defaults included` });
      }
    }
  });

