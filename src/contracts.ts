// ---- stock faults: "ok" | "down" | "fail-first:<N>" (N >= 1) | "flaky:<rate>" (0 < rate < 1)
export type StockFault = { kind: "ok" } | { kind: "down" } | { kind: "fail_first"; n: number } | { kind: "flaky"; rate: number };
/** Parses a fault spec. Throws Error("invalid stock fault: <spec>") on anything else. */
export function parseStockFault(spec: string): StockFault {
  if (spec === "ok") return { kind: "ok" };
  if (spec === "down") return { kind: "down" };
  const failFirst = /^fail-first:([1-9][0-9]*)$/.exec(spec);
  if (failFirst !== null) {
    const n = Number(failFirst[1]);
    if (Number.isSafeInteger(n)) return { kind: "fail_first", n };
  }
  const flaky = /^flaky:([0-9]+(?:\.[0-9]+)?|\.[0-9]+)$/.exec(spec);
  if (flaky !== null) {
    const rate = Number(flaky[1]);
    // A rate below 0.000001 prints in exponent form, which this parser doesn't read, so it's refused here:
    // every fault this function accepts survives formatStockFault and a second parse.
    if (rate > 0 && rate < 1 && /^[0-9.]+$/.test(String(rate))) return { kind: "flaky", rate };
  }
  throw new Error(`invalid stock fault: ${spec}`);
}
/** The inverse of parseStockFault. */
export function formatStockFault(f: StockFault): string {
  switch (f.kind) {
    case "ok": return "ok";
    case "down": return "down";
    case "fail_first": return `fail-first:${f.n}`;
    case "flaky": return `flaky:${f.rate}`;
  }
}
/** The key one RFQ line has in the simulated inventory service. */
export function stockLineKey(materialCode: string, partNumber: string, quantity: number): string {
  return `${materialCode}|${partNumber.trim().toUpperCase()}|${quantity}`;
}
/** Decides one backend attempt. attemptNo counts from 1 per key per server process. */
export function stockAttemptFails(fault: StockFault, faultSeed: number, key: string, attemptNo: number): boolean {
  switch (fault.kind) {
    case "ok": return false;
    case "down": return true;
    case "fail_first": return attemptNo <= fault.n;
    case "flaky": return faultDraw(`${faultSeed}|${key}|${attemptNo}`) < fault.rate;
  }
}
export type ExpectedStock = { verified: boolean; attempts: number }; // attempts: first success, else STOCK_ATTEMPTS
/** Replays the schedule for the one check_stock call a line gets: attempts 1..STOCK_ATTEMPTS, stopping at the first success. */
export function expectedStock(fault: StockFault, faultSeed: number, key: string): ExpectedStock {
  for (let attemptNo = 1; attemptNo <= STOCK_ATTEMPTS; attemptNo++) {
    if (!stockAttemptFails(fault, faultSeed, key, attemptNo)) return { verified: true, attempts: attemptNo };
  }
  return { verified: false, attempts: STOCK_ATTEMPTS };
}

